"""Build a (state, action) dataset from NSG-docker-state-creator trajectories.

The state creator has already done the pairing: every action record names its
`state_before` and `state_after`, and each `trajectory/states/state-NNNNNN/`
holds a complete graph in the same schema as the live state. This module walks
that sequence, projects both states, diffs them in NetSecGame terms, labels the
transition (see `labeling`), and writes rows whose source of truth is the
*graph*, never a tensor and never a projected state:

    <out>/pairs.jsonl              one row per labelled action
    <out>/graphs/state-NNNNNN.json copied state graphs, hashed
    <out>/unmappable.jsonl         observed behaviour NSG cannot express
    <out>/report.json              yields, label-source matrix, extension list

`projection_cache` inside a row records the adapter version and config that
produced it and can be regenerated by any future adapter from the copied graph,
so a mapping change re-derives the dataset instead of invalidating it.
"""

from __future__ import annotations

from collections import Counter, defaultdict
from dataclasses import dataclass, field
import hashlib
import json
import os
import shutil
from typing import Any, Dict, Iterable, Iterator, List, Optional, Sequence, Tuple

from .candidates import breakdown, enumerate_actions, support_status
from .labeling import CommandFacts, Label, LabelResult, Unmappable, label_transition, parse_command
from .state_adapter import AdapterConfig, Projection, project_graph_to_game_state
from .state_diff import diff_states, lost_knowledge

PAIR_SCHEMA_VERSION = "nsg-surrogate-pair/1"
ADAPTER_VERSION = "nsg_surrogate.state_adapter/1"

#: Attribution quality of the state creator's action sources, best first.
SOURCE_PRIORITY = {
    "bash-command": 0,
    "process-lifecycle": 1,
    "ebpf-exec-fallback": 2,
    "syscall-activity": 3,
}


@dataclass
class TransitionActions:
    """The action records the state creator attributed to one transition."""

    records: List[Dict[str, Any]] = field(default_factory=list)
    collapsed: int = 0
    sources: Counter = field(default_factory=Counter)

    @property
    def commands(self) -> List[CommandFacts]:
        parsed = [parse_command(record) for record in self.records]
        return [facts for facts in parsed if facts is not None]


@dataclass
class DatasetReport:
    run_id: str = ""
    states: int = 0
    transitions: int = 0
    action_records: int = 0
    actions_after_dedupe: int = 0
    action_sources: Dict[str, int] = field(default_factory=dict)
    labels: int = 0
    labels_by_source: Dict[str, int] = field(default_factory=dict)
    labels_by_type: Dict[str, int] = field(default_factory=dict)
    labels_by_translator_support: Dict[str, int] = field(default_factory=dict)
    rejected: Dict[str, int] = field(default_factory=dict)
    unmappable: Dict[str, int] = field(default_factory=dict)
    transitions_with_no_label: int = 0
    transitions_with_empty_diff: int = 0
    knowledge_lost: Dict[str, int] = field(default_factory=dict)
    adapter_notes: Dict[str, int] = field(default_factory=dict)

    def as_dict(self) -> Dict[str, Any]:
        return {
            "run_id": self.run_id,
            "states": self.states,
            "transitions": self.transitions,
            "action_records": self.action_records,
            "actions_after_dedupe": self.actions_after_dedupe,
            "action_sources": self.action_sources,
            "labels": self.labels,
            "labels_by_source": self.labels_by_source,
            "labels_by_type": self.labels_by_type,
            "labels_by_translator_support": self.labels_by_translator_support,
            "rejected": self.rejected,
            "unmappable": self.unmappable,
            "transitions_with_no_label": self.transitions_with_no_label,
            "transitions_with_empty_diff": self.transitions_with_empty_diff,
            "knowledge_lost": self.knowledge_lost,
            "adapter_notes": self.adapter_notes,
        }


@dataclass
class BuildResult:
    rows: List[Dict[str, Any]] = field(default_factory=list)
    unmappable: List[Dict[str, Any]] = field(default_factory=list)
    report: DatasetReport = field(default_factory=DatasetReport)


# ── trajectory walking ──────────────────────────────────────────────────────


def read_sequence(trajectory_dir: str) -> List[Dict[str, Any]]:
    path = os.path.join(trajectory_dir, "sequence.jsonl")
    with open(path, "r", encoding="utf-8") as handle:
        return [json.loads(line) for line in handle if line.strip()]


def state_graph_path(trajectory_dir: str, state_id: str) -> str:
    return os.path.join(trajectory_dir, "states", state_id, "graph.json")


def group_actions(
    sequence: Sequence[Dict[str, Any]],
    trajectory_dir: str,
    max_records_per_transition: Optional[int] = None,
) -> Dict[Tuple[str, str], TransitionActions]:
    """Group action records by the (state_before, state_after) they bridge.

    Deduplication matters more than it looks: a single command shows up as one
    `bash-command` record plus a swarm of `ebpf-exec-fallback` records for the
    same execution (the sample run has 36,123 of the latter against 28 of the
    former). Records are collapsed by command text, keeping the one from the
    highest-quality source, so the dataset is not dominated by repeats.
    """
    grouped: Dict[Tuple[str, str], TransitionActions] = defaultdict(TransitionActions)

    for entry in sequence:
        if entry.get("kind") != "action":
            continue
        key = (str(entry.get("state_before", "")), str(entry.get("state_after", "")))
        bucket = grouped[key]

        record_path = entry.get("record")
        if not record_path:
            continue
        full_path = os.path.join(trajectory_dir, record_path)
        if not os.path.isfile(full_path):
            continue
        with open(full_path, "r", encoding="utf-8") as handle:
            record = json.load(handle)

        bucket.sources[str(record.get("source", "?"))] += 1
        if (
            max_records_per_transition is not None
            and len(bucket.records) >= max_records_per_transition
        ):
            bucket.collapsed += 1
            continue
        bucket.records.append(record)

    for bucket in grouped.values():
        bucket.records, collapsed = _dedupe_records(bucket.records)
        bucket.collapsed += collapsed
    return dict(grouped)


def _dedupe_records(records: Sequence[Dict[str, Any]]) -> Tuple[List[Dict[str, Any]], int]:
    best: Dict[str, Dict[str, Any]] = {}
    for record in records:
        command = record.get("command") or {}
        key = str(command.get("shell_text") or command.get("argv") or record.get("id"))
        incumbent = best.get(key)
        if incumbent is None:
            best[key] = record
            continue
        if _source_rank(record) < _source_rank(incumbent):
            best[key] = record
    ordered = sorted(best.values(), key=lambda record: str(record.get("started_at", "")))
    return ordered, len(records) - len(ordered)


def _source_rank(record: Dict[str, Any]) -> int:
    return SOURCE_PRIORITY.get(str(record.get("source", "")), 99)


def transitions(
    sequence: Sequence[Dict[str, Any]], grouped: Optional[Dict[Tuple[str, str], Any]] = None
) -> List[Tuple[str, str]]:
    """The (state_before, state_after) pairs to label.

    Taken from the action records themselves, not from consecutive state ids.
    Two shapes would be lost otherwise:

    * **self-loops.** An action that changed nothing is recorded with
      `state_before == state_after` (`nmap -sP` sits at
      `state-000005 -> state-000005` in the strategic sample run). These are the
      no-effect actions a dataset most needs, and pairing consecutive states
      drops every one of them.
    * **jumps.** A settle window can span several snapshots, so
      `apt install nmap` bridges `state-000003 -> state-000005` directly.

    Falls back to consecutive pairs when no action records are available, so a
    trajectory of states alone still yields transitions.
    """
    if grouped:
        return sorted(
            key for key in grouped if all(part for part in key)
        )
    state_ids = [str(entry["id"]) for entry in sequence if entry.get("kind") == "state"]
    return list(zip(state_ids, state_ids[1:]))


# ── building ────────────────────────────────────────────────────────────────


def build(
    observation_root: str,
    config: Optional[AdapterConfig] = None,
    run_id: Optional[str] = None,
    max_records_per_transition: Optional[int] = 200,
) -> BuildResult:
    """Walk one observation run and produce labelled pairs plus a report."""
    config = config or AdapterConfig()
    trajectory_dir = _trajectory_dir(observation_root)
    run_id = run_id or os.path.basename(os.path.normpath(observation_root))

    sequence = read_sequence(trajectory_dir)
    grouped = group_actions(sequence, trajectory_dir, max_records_per_transition)
    state_pairs = transitions(sequence, grouped)

    result = BuildResult()
    report = result.report
    report.run_id = run_id
    report.states = sum(1 for entry in sequence if entry.get("kind") == "state")
    report.transitions = len(state_pairs)
    report.action_records = sum(sum(b.sources.values()) for b in grouped.values())
    report.actions_after_dedupe = sum(len(b.records) for b in grouped.values())
    source_totals: Counter = Counter()
    for bucket in grouped.values():
        source_totals.update(bucket.sources)
    report.action_sources = dict(source_totals)

    label_sources: Counter = Counter()
    label_types: Counter = Counter()
    support: Counter = Counter()
    rejected: Counter = Counter()
    unmappable: Counter = Counter()
    lost_totals: Counter = Counter()
    adapter_notes: Counter = Counter()

    projections: Dict[str, Projection] = {}
    config_hash = _config_hash(config)

    def projection_for(state_id: str) -> Optional[Projection]:
        if state_id in projections:
            return projections[state_id]
        path = state_graph_path(trajectory_dir, state_id)
        if not os.path.isfile(path):
            return None
        with open(path, "r", encoding="utf-8") as handle:
            graph = json.load(handle)
        projection = project_graph_to_game_state(graph, config=config, source=path)
        projections[state_id] = projection
        return projection

    for before_id, after_id in state_pairs:
        before_projection = projection_for(before_id)
        after_projection = projection_for(after_id)
        if before_projection is None or after_projection is None:
            continue

        for note in before_projection.report.notes:
            adapter_notes[_note_key(note)] += 1

        before, after = before_projection.state, after_projection.state
        diff = diff_states(before, after)
        for category, count in lost_knowledge(before, after).items():
            if count:
                lost_totals[category] += count

        bucket = grouped.get((before_id, after_id)) or TransitionActions()
        docker_evidence = {
            "action_ids": [str(record.get("id")) for record in bucket.records[:8]],
            "action_record_count": sum(bucket.sources.values()),
            "action_sources": dict(bucket.sources),
            "changed_domains": sorted(
                {
                    domain
                    for record in bucket.records
                    for domain in (record.get("changed_domains") or ())
                }
            ),
            "causal_isolation": any(
                bool(record.get("causal_isolation")) for record in bucket.records
            ),
        }

        labelling = label_transition(
            before,
            after,
            diff,
            commands=bucket.commands,
            provenance=before_projection.provenance,
            docker_evidence=docker_evidence,
            states_differ=before_id != after_id,
        )

        if diff.empty:
            report.transitions_with_empty_diff += 1
        if not labelling.labels:
            report.transitions_with_no_label += 1

        candidate_actions = enumerate_actions(before)
        for index, label in enumerate(labelling.labels):
            row = _row(
                run_id=run_id,
                index=index,
                before_id=before_id,
                after_id=after_id,
                before_projection=before_projection,
                after_projection=after_projection,
                diff=diff,
                label=label,
                alternatives=[
                    other for other in labelling.labels if other is not label
                ],
                candidate_actions=candidate_actions,
                config_hash=config_hash,
                trajectory_dir=trajectory_dir,
            )
            result.rows.append(row)
            label_sources[label.label_source] += 1
            label_types[label.action.type.name] += 1
            support[support_status(label.action)] += 1

        for label, reason in labelling.rejected:
            rejected[f"{label.action.type.name}: {reason}"] += 1

        for item in labelling.unmappable:
            unmappable[item.category] += 1
            result.unmappable.append(
                dict(
                    item.as_dict(),
                    run_id=run_id,
                    state_before=before_id,
                    state_after=after_id,
                )
            )

    report.labels = len(result.rows)
    report.labels_by_source = dict(label_sources)
    report.labels_by_type = dict(sorted(label_types.items()))
    report.labels_by_translator_support = dict(support)
    report.rejected = dict(rejected.most_common(20))
    report.unmappable = dict(unmappable.most_common())
    report.knowledge_lost = dict(lost_totals)
    report.adapter_notes = dict(adapter_notes.most_common(10))
    return result


def _row(
    run_id: str,
    index: int,
    before_id: str,
    after_id: str,
    before_projection: Projection,
    after_projection: Projection,
    diff,
    label: Label,
    alternatives: Sequence[Label],
    candidate_actions: Sequence[Any],
    config_hash: str,
    trajectory_dir: str,
) -> Dict[str, Any]:
    return {
        "schema_version": PAIR_SCHEMA_VERSION,
        "run_id": run_id,
        "pair_id": f"{run_id}:{before_id}->{after_id}:{index}",
        "state_before": _state_ref(before_id, before_projection, trajectory_dir),
        "state_after": _state_ref(after_id, after_projection, trajectory_dir),
        "nsg_diff": diff.summary(),
        "nsg_diff_categories": list(diff.changed_categories),
        "label": label.as_dict(),
        "alternatives": [other.as_dict() for other in alternatives],
        "projection_cache": {
            "adapter_version": ADAPTER_VERSION,
            "config_hash": config_hash,
            "game_state": canonical_game_state(before_projection.state),
            "candidate_count": len(candidate_actions),
            "candidate_breakdown": breakdown(candidate_actions),
            "label_in_candidates": True,
        },
    }


def _state_ref(state_id: str, projection: Projection, trajectory_dir: str) -> Dict[str, Any]:
    return {
        "id": state_id,
        "graph": f"graphs/{state_id}.json",
        "graph_source": os.path.relpath(projection.report.source, trajectory_dir),
        "sha256": _file_sha256(projection.report.source),
        "generated_at": projection.report.generated_at,
        "detail_level": projection.report.detail_level,
    }


def write(result: BuildResult, out_dir: str, trajectory_dir: str) -> Dict[str, str]:
    """Write a self-contained dataset directory.

    State graphs are copied in rather than referenced: observation directories
    are rotated and rebuilt, and a dataset that points at one is a dataset with
    an expiry date.
    """
    graphs_dir = os.path.join(out_dir, "graphs")
    os.makedirs(graphs_dir, exist_ok=True)

    copied: set = set()
    for row in result.rows:
        for side in ("state_before", "state_after"):
            state_id = row[side]["id"]
            if state_id in copied:
                continue
            source = state_graph_path(trajectory_dir, state_id)
            if os.path.isfile(source):
                shutil.copyfile(source, os.path.join(graphs_dir, f"{state_id}.json"))
                copied.add(state_id)

    paths = {
        "pairs": os.path.join(out_dir, "pairs.jsonl"),
        "unmappable": os.path.join(out_dir, "unmappable.jsonl"),
        "report": os.path.join(out_dir, "report.json"),
    }
    with open(paths["pairs"], "w", encoding="utf-8") as handle:
        for row in result.rows:
            handle.write(json.dumps(row, sort_keys=True) + "\n")
    with open(paths["unmappable"], "w", encoding="utf-8") as handle:
        for item in result.unmappable:
            handle.write(json.dumps(item, sort_keys=True) + "\n")
    with open(paths["report"], "w", encoding="utf-8") as handle:
        json.dump(result.report.as_dict(), handle, indent=2, sort_keys=True)
    return paths


def read_pairs(path: str) -> Iterator[Dict[str, Any]]:
    """Stream rows back. Kept here so consumers share one reader."""
    with open(path, "r", encoding="utf-8") as handle:
        for line in handle:
            if line.strip():
                yield json.loads(line)


# ── helpers ─────────────────────────────────────────────────────────────────


def canonical_game_state(state) -> Dict[str, Any]:
    """`GameState` as JSON-ready data with every list deterministically ordered.

    `GameState.as_json` walks sets, so its list order varies between processes
    (string hashing is randomised per interpreter). The states compare equal but
    the files do not, which makes dataset diffs noisy and any byte comparison of
    a cached projection a coin flip. Sorting by string form fixes both.
    """
    raw = json.loads(state.as_json())
    return {
        key: sorted(value, key=lambda item: json.dumps(item, sort_keys=True))
        if isinstance(value, list)
        else {
            inner_key: sorted(
                inner_value, key=lambda item: json.dumps(item, sort_keys=True)
            )
            if isinstance(inner_value, list)
            else inner_value
            for inner_key, inner_value in sorted(value.items())
        }
        if isinstance(value, dict)
        else value
        for key, value in sorted(raw.items())
    }


def _trajectory_dir(observation_root: str) -> str:
    for candidate in (
        os.path.join(observation_root, "trajectory"),
        observation_root,
    ):
        if os.path.isfile(os.path.join(candidate, "sequence.jsonl")):
            return candidate
    raise FileNotFoundError(f"no trajectory/sequence.jsonl under {observation_root}")


def _config_hash(config: AdapterConfig) -> str:
    payload = json.dumps(
        {
            "min_confidence": config.min_confidence,
            "include_inferred_networks": config.include_inferred_networks,
            "excluded_cidrs": sorted(config.excluded_cidrs),
            "require_confirmed_data": config.require_confirmed_data,
            "data_path_denylist": list(config.data_path_denylist),
            "max_data_per_host": config.max_data_per_host,
            "scope_cidrs": sorted(config.scope_cidrs),
            "external_hosts": sorted(config.external_hosts),
            "treat_external_as_controlled": config.treat_external_as_controlled,
            "agent_id": config.agent_id,
        },
        sort_keys=True,
    )
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()[:16]


def _file_sha256(path: str) -> str:
    digest = hashlib.sha256()
    try:
        with open(path, "rb") as handle:
            for chunk in iter(lambda: handle.read(65536), b""):
                digest.update(chunk)
    except OSError:
        return ""
    return digest.hexdigest()


def _note_key(note: str) -> str:
    """Collapse adapter notes that differ only by host or count."""
    for marker in (" has ", " also claims ", " block node(s)", " of "):
        if marker in note:
            return note.split(marker)[0] + marker.rstrip() + " …"
    return note[:80]
